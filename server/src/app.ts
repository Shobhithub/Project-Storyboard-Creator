import express from 'express';
import cookieParser from 'cookie-parser';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import mongoose from 'mongoose';
import { env } from './config.js';
import { api } from './routes.js';
import { errorHandler, HttpError, notFound } from './errors.js';

const here=path.dirname(fileURLToPath(import.meta.url));
export const app=express();
app.disable('x-powered-by');
app.set('trust proxy',env.NODE_ENV==='production'?1:false);
app.use(helmet({crossOriginResourcePolicy:{policy:'cross-origin'},contentSecurityPolicy:env.NODE_ENV==='production'?undefined:false}));
app.use(cors({origin:(origin,callback)=>origin&&origin!==env.CLIENT_URL?callback(new HttpError(403,'This origin is not allowed.','ORIGIN_NOT_ALLOWED')):callback(null,true),credentials:true,methods:['GET','POST','PATCH','DELETE','OPTIONS'],allowedHeaders:['Content-Type','Idempotency-Key']}));
app.use((req,_res,next)=>{if(['POST','PATCH','DELETE'].includes(req.method)&&req.get('Origin')&&req.get('Origin')!==env.CLIENT_URL)return next(new HttpError(403,'Cross-origin state changes are not allowed.','CSRF_ORIGIN_REJECTED'));next();});
app.use(express.json({limit:'1mb',strict:true}));
app.use(express.urlencoded({extended:false,limit:'1mb'}));
app.use(cookieParser());
app.get('/api/health',(_req,res)=>res.status(mongoose.connection.readyState===1?200:503).json({ok:mongoose.connection.readyState===1,database:mongoose.connection.readyState===1?'connected':'disconnected'}));
app.use('/api',rateLimit({windowMs:15*60*1000,limit:300,standardHeaders:'draft-8',legacyHeaders:false,message:{error:{code:'RATE_LIMITED',message:'Too many requests. Please wait and retry.'}}}));
app.use('/api/auth',rateLimit({windowMs:15*60*1000,limit:20,standardHeaders:'draft-8',legacyHeaders:false,message:{error:{code:'AUTH_RATE_LIMITED',message:'Too many sign-in attempts. Please wait and retry.'}}}));
app.use('/api',api);
const dist=path.resolve(here,'../../dist');
app.use(express.static(dist,{index:false,fallthrough:true}));
app.use('/api',notFound);
app.get('*path',(req,res,next)=>{if(req.path.startsWith('/api/'))return next();res.sendFile(path.join(dist,'index.html'),err=>err&&next(err));});
app.use(errorHandler);
export default app;
